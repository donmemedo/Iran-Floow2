export const dict: Record<Locale, Dict> = { fa, en };

const nf = (l: Locale, o?: Intl.NumberFormatOptions) => new Intl.NumberFormat(l === "fa" ? "fa-IR" : "en-US", o);
export const num = (l: Locale, n: number, o?: Intl.NumberFormatOptions) => nf(l, o).format(n);
export const money = (l: Locale, n: number) => `${nf(l, { notation: "compact", maximumFractionDigits: 1 }).format(n)} ${dict[l].toman}`;
export const jalali = (l: Locale, iso: string) =>
  new Intl.DateTimeFormat(l === "fa" ? "fa-IR-u-ca-persian" : "en-GB", { day: "numeric", month: "long", year: "numeric" }).format(new Date(iso));
/** Users type Persian/Arabic digits; the API wants ASCII. */
export const toLatinDigits = (s: string) =>
  s.replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d))).replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)));
